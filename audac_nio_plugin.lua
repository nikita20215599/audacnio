-- Utility: bit32 is available in Q-SYS Lua runtime
local function crc16(data)
  local crc = 0xFFFF
  for i = 1, #data do
    crc = bit32.bxor(crc, string.byte(data, i))
    for _ = 1, 8 do
      local lsb = bit32.band(crc, 1)
      crc = bit32.rshift(crc, 1)
      if lsb ~= 0 then
        crc = bit32.bxor(crc, 0xA001)
      end
    end
  end
  return string.format("%04X", bit32.band(crc, 0xFFFF))
end

local function trim(s)
  return (s and s:gsub("^%s+", ""):gsub("%s+$", "")) or ""
end

-- Transport abstraction (UDP-focused; easily adapted for TCP if needed)
local Transport = {}
Transport.__index = Transport

function Transport:new(onData, onStatus)
  local t = {
    socket = nil,
    onData = onData,
    onStatus = onStatus,
    connected = false,
    buffer = ""
  }
  setmetatable(t, Transport)
  return t
end

function Transport:connect(host, port, localPort)
  if self.socket then
    self.socket:Close()
    self.socket = nil
  end
  self.socket = UdpSocket.New()
  self.socket.ReadTimeout = 1
  self.socket.WriteTimeout = 1
  self.socket.EventHandler = function(sock, evt)
    if evt == UdpSocket.Events.Closed then
      self.connected = false
      if self.onStatus then self.onStatus("Closed") end
    elseif evt == UdpSocket.Events.Error then
      self.connected = false
      if self.onStatus then self.onStatus("Error: " .. (sock.LastError or "Unknown")) end
    elseif evt == UdpSocket.Events.Data then
      local data = sock:Read(sock:BytesAvailable()) or ""
      if #data > 0 then
        self.buffer = self.buffer .. data
        if self.onData then
          local remainder = self.onData(self.buffer)
          if type(remainder) == "string" then
            self.buffer = remainder
          else
            self.buffer = ""
          end
        end
      end
    end
  end
  local ok, err = pcall(function() self.socket:Open(localPort or 0) end)
  self.host = host
  self.port = port
  self.connected = ok
  if not ok and self.onStatus then
    self.onStatus("Error: " .. tostring(err))
  elseif ok and self.onStatus then
    self.onStatus("Connected")
  end
end

function Transport:send(payload)
  if self.socket and self.connected then
    self.socket:Write(payload, self.host, self.port)
  end
end

function Transport:close()
  if self.socket then
    self.socket:Close()
    self.connected = false
  end
end

-- Command builder/parser
local function build_command(destAddr, target, command, args, requestType)
  local destination = string.format("NIO240>%s", destAddr or "1")
  local source = "QSYS"
  local msgType = requestType or "SET_REQ"
  local arguments = args or ""
  local frame = string.format("#|%s|%s|%s^%s^%s|%s|", destination, source, msgType, target, command, arguments)
  local crc = crc16(frame)
  return frame .. crc .. "|\r\n"
end

local function parse_response(raw)
  local responses = {}
  local remainder = ""
  local idx = 1
  while true do
    local s, e = raw:find("\r?\n", idx)
    if not s then
      remainder = raw:sub(idx)
      break
    end
    local line = raw:sub(idx, s - 1)
    idx = e + 1
    if line:sub(1, 1) == "#" then
      local parts = {}
      for part in line:gmatch("([^|]+)|") do
        table.insert(parts, part)
      end
      if #parts >= 5 then
        local destination = parts[1]:gsub("^#", "")
        local source = parts[2]
        local typeBlock = parts[3]
        local targetCommand = parts[4]
        local args = parts[5]
        local tTarget, tCommand = targetCommand:match("([^%^]+)%^(.*)")
        local msgType, target, command = typeBlock:match("([^%^]+)%^([^%^]+)%^(.*)")
        table.insert(responses, {
          destination = destination,
          source = source,
          msgType = msgType or typeBlock,
          target = target or tTarget,
          command = command or tCommand,
          args = args
        })
      end
    end
  end
  return responses, remainder
end

