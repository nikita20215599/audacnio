-- Command queue to rate limit
local commandQueue = {}
local function enqueueCommand(cmd)
  table.insert(commandQueue, cmd)
end

local function processQueue(transport)
  if #commandQueue == 0 then return end
  local cmd = table.remove(commandQueue, 1)
  transport:send(cmd)
end

-- Control bindings
local transport = Transport:new(function(raw)
  local responses, remainder = parse_response(raw)
  transport.buffer = remainder or ""
  for _, rsp in ipairs(responses) do
    local target = rsp.target or ""
    local command = rsp.command or ""
    local args = trim(rsp.args or "")
    local function updateChannel(base, idx)
      local key = string.format("%s_%d", base, idx)
      local muteKey = key .. "_mute"
      local volKey = key .. "_vol"
      if command == "MUTE" then
        local val = args == "1"
        channelState[key].mute = val
        if Controls[muteKey] then Controls[muteKey].Boolean = val end
      elseif command == "VOLUME" then
        local num = tonumber(args)
        if num then
          channelState[key].vol = num
          if Controls[volKey] then Controls[volKey].Value = num end
        end
      end
    end

    local baseTarget, indexStr = target:match("([^>]+)>(%d+)")
    if baseTarget and indexStr then
      local idx = tonumber(indexStr)
      if baseTarget == "INPUT_LINE" then updateChannel("inputs_line", idx) end
      if baseTarget == "INPUT_DANTE" then updateChannel("inputs_dante", idx) end
      if baseTarget == "INPUT_BLUETOOTH" then updateChannel("inputs_bt", idx) end
      if baseTarget == "OUTPUT_DANTE" then updateChannel("outputs_dante", idx) end
    elseif target == "ALL_IN" or target == "ALL_OUT" then
      local val = args == "1"
      if target == "ALL_IN" then Controls.AllInputsMute.Boolean = val end
      if target == "ALL_OUT" then Controls.AllOutputsMute.Boolean = val end
    end
  end
  return transport.buffer
end, function(status)
  if Controls.Online then
    Controls.Online.Boolean = status == "Connected"
  end
  if status ~= "Connected" and Controls.LastError then
    Controls.LastError.String = status
  end
  if status == "Connected" then
    pollTimer:Start(Properties.PollIntervalMs.Value)
    queueTimer:Start(200)
    reconnectTimer:Stop()
  else
    pollTimer:Stop()
    reconnectTimer:Stop()
    reconnectTimer:Start(Properties.ReconnectBackoffMs.Value)
  end
end)

