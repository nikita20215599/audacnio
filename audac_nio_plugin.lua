    local addr = Properties.DeviceAddress.Value
    local val = ctrl.Boolean and "1" or "0"
    enqueueCommand(build_command(addr, "ALL_IN", "MUTE", val, "SET_REQ"))
  end
  Controls.AllOutputsMute.EventHandler = function(ctrl)
    local addr = Properties.DeviceAddress.Value
    local val = ctrl.Boolean and "1" or "0"
    enqueueCommand(build_command(addr, "ALL_OUT", "MUTE", val, "SET_REQ"))
  end

  for key, def in pairs(channelDefinitions) do
    for i = 1, def.count do
      local base = string.format("%s_%d", key, i)
      local target = string.format("%s>%d>VOLUME>1", def.baseTarget, i)
      local muteCtrl = Controls[base .. "_mute"]
      local volCtrl = Controls[base .. "_vol"]
      if muteCtrl then
        muteCtrl.EventHandler = function(c)
          local addr = Properties.DeviceAddress.Value
          local val = c.Boolean and "1" or "0"
          enqueueCommand(build_command(addr, target, "MUTE", val, "SET_REQ"))
        end
      end
      if volCtrl then
        volCtrl.EventHandler = function(c)
          local addr = Properties.DeviceAddress.Value
          local val = string.format("%.1f", c.Value)
          enqueueCommand(build_command(addr, target, "VOLUME", val, "SET_REQ"))
        end
      end
    end
  end

  for _, pair in ipairs(stereoPairs) do
    local modeCtrl = Controls[pair.key .. "_mode"]
    local muteCtrl = Controls[pair.key .. "_mute"]
    local volCtrl = Controls[pair.key .. "_vol"]
    if modeCtrl then
      modeCtrl.EventHandler = function(c)
        pairModeState[pair.key] = c.String
      end
    end
    if muteCtrl then
      muteCtrl.EventHandler = function(c)
        handleStereoSync(pair.key, "mute", c.Boolean)
        for _, member in ipairs(pair.members) do
          local mCtrl = Controls[member .. "_mute"]
          if mCtrl then mCtrl.EventHandler(mCtrl) end
        end
      end
    end
    if volCtrl then
      volCtrl.EventHandler = function(c)
        handleStereoSync(pair.key, "vol", c.Value)
        for _, member in ipairs(pair.members) do
          local vCtrl = Controls[member .. "_vol"]
          if vCtrl then vCtrl.EventHandler(vCtrl) end
        end
      end
    end
  end
