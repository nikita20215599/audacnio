-- Stereo helpers
local function handleStereoSync(pairKey, controlType, value)
  local mode = pairModeState[pairKey]
  if mode ~= "Linked" then return end
  for _, pair in ipairs(stereoPairs) do
    if pair.key == pairKey then
      for _, member in ipairs(pair.members) do
        if controlType == "mute" then
          local ctrl = Controls[member .. "_mute"]
          if ctrl then ctrl.Boolean = value end
        elseif controlType == "vol" then
          local ctrl = Controls[member .. "_vol"]
          if ctrl then ctrl.Value = value end
        end
      end
    end
  end
end

